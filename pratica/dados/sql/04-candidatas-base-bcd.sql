PRINT '##### (b1) subconsulta correlacionada - sem indice';
SELECT u.Id, u.DisplayName, (SELECT COUNT(*) FROM dbo.Posts p WHERE p.OwnerUserId = u.Id) AS Qtd FROM dbo.Users u WHERE u.Reputation >= 20000;
PRINT '##### (b2) JOIN + GROUP BY - sem indice';
SELECT u.Id, u.DisplayName, COUNT(p.Id) AS Qtd FROM dbo.Users u LEFT JOIN dbo.Posts p ON p.OwnerUserId = u.Id WHERE u.Reputation >= 20000 GROUP BY u.Id, u.DisplayName;
